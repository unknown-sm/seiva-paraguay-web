export const departamentosUnicos = Array.from(new Set(ciudadesParaguay.map(c => c.departamento))).sort()

// Helper to get cities for a department
export function getCiudadesPorDepartamento(departamento: string): string[] {
  return ciudadesParaguay
    .filter(c => c.departamento === departamento)
    .map(c => c.ciudad)
    .sort()
}

// Helper to parse selected value
export function parseCiudadSeleccionada(value: string): { departamento: string; ciudad: string } {
  const parts = value.split(' - ')
  if (parts.length >= 2) {
    const ciudad = parts[parts.length - 1]
    const departamento = parts.slice(0, -1).join(' - ')
    return { departamento, ciudad }
  }
  return { departamento: '', ciudad: value }
}
